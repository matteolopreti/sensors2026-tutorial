"""Single source for every demo number quoted in slides, handout and README.

Reads the frozen full-length runs (out/freeze/postfix2_s*.txt, phase 4 ms) and the phase sweep
(out/freeze/postfix2_sweep.txt) and writes out/freeze/NUMBERS.md: per metric and version, min-max over seeds,
plus per-version loss range over phases. Quote numbers only from NUMBERS.md.
Run: python freeze_numbers.py
"""
import re
from pathlib import Path

FREEZE = Path(__file__).parent / "out" / "freeze"
VERSIONS = ["truth", "V0", "V1", "V2", "V3", "V4"]


def table(path):
    """{metric: [value per column]} from the datasheet table of one run; n/a -> None."""
    rows = {}
    for line in path.read_text().splitlines():
        parts = line.split()
        if len(parts) == len(VERSIONS) + 1 and re.match(r"^[a-z][a-zA-Z0-9_]*$", parts[0]):
            try:
                rows[parts[0]] = [None if p == "n/a" else float(p) for p in parts[1:]]
            except ValueError:
                continue
    return rows


def rng(vals):
    vals = [v for v in vals if v is not None]
    if not vals:
        return "n/a"
    lo, hi = min(vals), max(vals)
    return f"{lo:.4g}" if lo == hi else f"{lo:.4g}–{hi:.4g}"


def main():
    runs = sorted(FREEZE.glob("postfix2_s[0-9].txt"))
    tables = [table(p) for p in runs]
    out = [f"# Frozen demo numbers (generated by freeze_numbers.py; do not edit)",
           f"Full length, phase 4 ms, seeds: {', '.join(p.stem[-1] for p in runs)}. Range = min–max over seeds.", "",
           "| metric | " + " | ".join(VERSIONS) + " |", "|---" * (len(VERSIONS) + 1) + "|"]
    for m in tables[0]:
        out.append(f"| {m} | " + " | ".join(rng([t[m][i] for t in tables if m in t]) for i in range(len(VERSIONS))) + " |")
    sweep = {}
    for line in (FREEZE / "postfix2_sweep.txt").read_text().splitlines():
        p = line.split()
        if len(p) == 5 and p[0].startswith("V") and p[1].replace(".", "").isdigit():
            sweep.setdefault(p[0], []).append((float(p[1]), float(p[2]), None if p[3] == "n/a" else float(p[3]), float(p[4])))
    out += ["", "## Phase sweep (seed 2, phase 0–18 ms)", "| version | lost true % | lost visible % | lag ms | phases with 0 % |",
            "|---|---|---|---|---|"]
    for v, rows in sweep.items():
        zero = ", ".join(f"{r[0]:g}" for r in rows if r[1] == 0) or "none"
        out.append(f"| {v} | {rng([r[1] for r in rows])} | {rng([r[2] for r in rows])} | {rng([r[3] for r in rows])} | {zero} |")
    (FREEZE / "NUMBERS.md").write_text("\n".join(out) + "\n")
    print("\n".join(out))


if __name__ == "__main__":
    main()
